// Single lookup — returns the nearest kommun (and its län) for a lat/lng.
// No distance cap: Sweden's 290 kommuner tile the whole country, so any
// real Swedish coordinate resolves to a meaningful kommun. Returns a
// fallback 'Okänd' pair for invalid coordinates (NaN lat/lng).
export function placeForLatLng(lat: number, lng: number): { kommun: string; lan: string } {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) {
    return { kommun: 'Okänd', lan: 'Okänd' };
  }
  const cosLat = Math.cos((lat * Math.PI) / 180);
  let best: Kommun | null = null;
  let bestDist2 = Infinity;
  for (const k of KOMMUNER) {
    const dLat = (k.lat - lat) * 111;
    const dLng = (k.lng - lng) * 111 * cosLat;
    const d2 = dLat * dLat + dLng * dLng;
    if (d2 < bestDist2) {
      bestDist2 = d2;
      best = k;
    }
  }
  return best ? { kommun: best.name, lan: best.lan } : { kommun: 'Okänd', lan: 'Okänd' };
}
